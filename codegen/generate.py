def success_response(op: dict):
    codes = sorted(c for c in op["responses"] if c.startswith("2"))
    return codes, [op["responses"][c] for c in codes]


def resolve_response(r: dict) -> dict:
    if "$ref" in r:
        return SPEC["components"]["responses"][ref_name(r["$ref"])]
    return r


def build_endpoint(m: dict) -> dict:
    op = SPEC["paths"][m["path"]][m["verb"]]
    path_level = SPEC["paths"][m["path"]].get("parameters", [])
    params = path_level + op.get("parameters", [])
    path_params = [p for p in params if p["in"] == "path"]
    order = re.findall(r"\{(\w+)\}", m["path"])
    path_params.sort(key=lambda p: order.index(p["name"]))

    codes, responses = success_response(op)
    responses = [resolve_response(r) for r in responses]
    content: dict = {}
    for r in responses:
        content.update(r.get("content") or {})

    ret = m["ret_text"]
    kind = "json"
    item_schema = None
    if ret == "None":
        kind = "unit"
    elif ret == "BinaryAPIResponse":
        kind = "binary"
    elif "text/event-stream" in content:
        kind = "sse"
        item_schema = content["text/event-stream"]["schema"]
    elif ret.startswith("SyncOffsetPagination["):
        kind = "offset_page"
        item_schema = content["application/json"]["schema"]["items"]
    elif ret.startswith("SyncPageTokenPagination["):
        kind = "token_page"
        item_schema = content["application/json"]["schema"]["items"]
    else:
        js = content.get("application/json")
        if js is None:
            warn(f"{m['verb']} {m['path']}: return {ret} without JSON content; treating as unit")
            kind = "unit"
        else:
            item_schema = js["schema"]
            if any(c == "204" for c in codes):
                kind = "optional"
    ret_name = re.sub(r"^Sync\w+Pagination\[(\w+)\]$", r"\1", ret)

    body = op.get("requestBody")
    body_kind = None
    body_schema = None
    if body:
        ct = list(body["content"].keys())[0]
        body_schema = body["content"][ct].get("schema", {})
        body_kind = {"application/json": "json", "multipart/form-data": "multipart",
                     "application/octet-stream": "bytes"}.get(ct)
        if body_kind is None:
            warn(f"{m['verb']} {m['path']}: unsupported body content type {ct}")

    return {
        **m,
        "op": op,
        "path_params": path_params,
        "query_params": [p for p in params if p["in"] == "query"],
        "header_params": [p for p in params if p["in"] == "header"],
        "codes": codes,
        "kind": kind,
        "item_schema": item_schema,
        "ret_name": ret_name,
        "body_kind": body_kind,
        "body_schema": body_schema,
    }


def params_name(ep: dict) -> tuple[tuple, str]:
    if ep["params_link"]:
        return module_of(ep["params_link"]), pascal(ep["params_link"].split("/")[-1])
    prefix = re.sub(r"Response$", "", ep["ret_name"]) if ep["ret_name"].endswith("Response") else \
        pascal("_".join(ep["resource"])) + pascal(ep["name"])
    warn(f"{ep['verb']} {ep['path']}: no params link in api.md; naming params {prefix}Params")
    return ep["ret_module"], prefix + "Params"


def build_params(ep: dict):
    """Build the params struct for an endpoint. Return None when the endpoint
    takes no params besides path params."""
    has_fields = ep["query_params"] or ep["header_params"] or ep["body_kind"] in ("json", "multipart")
    if not has_fields:
        return None
    module, name = params_name(ep)
    name = claim(module, name)
    multipart = ep["body_kind"] == "multipart"
    fields = []
    used = set()

    def add(f):
        while f["name"] in used:
            f["name"] += "_"
        used.add(f["name"])
        fields.append(f)

    for i, p in enumerate(ep["query_params"] + ep["header_params"]):
        schema = p.get("schema", {})
        add({
            "name": snake(p["name"]),
            "wire": p["name"],
            "ty": type_of(schema, module, name.removesuffix("Params") + pascal(p["name"])),
            "required": p.get("required", False),
            "req_index": i - 10_000,
            "nullable": False,
            "doc": p.get("description"),
            "const": None,
            "location": p["in"],
            "explode": p["in"] == "query" and resolve(schema).get("type") == "array"
            and p.get("explode", p.get("style", "form") == "form") is not False
            and "style" not in p and "explode" not in p,
            "file": False,
        })
        if p["in"] == "query" and p.get("style") == "deepObject":
            fields[-1]["explode"] = False

    body_union = False
    if ep["body_kind"] in ("json", "multipart"):
        schema = ep["body_schema"]
        m = merged_object(schema)
        sr = resolve(schema)
        is_union = ("oneOf" in sr or "anyOf" in sr) and not ("properties" in sr and is_constraint_only(sr.get("oneOf") or sr.get("anyOf")))
        if m is not None and not is_union:
            props, required = m
            if "$ref" in schema and not multipart:
                comp = component_ref(ref_name(schema["$ref"]))
                cdef = TYPES[(comp[1], comp[2])]
                body_fields = [dict(f) for f in cdef["fields"]] if cdef["kind"] == "struct" else \
                    build_fields(props, required, module, name.removesuffix("Params"))
            else:
                body_fields = build_fields(props, required, module, name.removesuffix("Params"), multipart)
            for f in body_fields:
                add(f)
        else:
            body_union = True
            add({
                "name": "body",
                "wire": "body",
                "ty": type_of(schema, module, name.removesuffix("Params") + "Body"),
                "required": True,
                "nullable": False,
                "doc": "The request body.",
                "const": None,
                "location": "body_union",
                "explode": False,
                "file": False,
            })

    TYPES[(module, name)] = {
        "kind": "struct",
        "fields": fields,
        "doc": f"Parameters for `{'.'.join(ep['resource'])}.{ep['name']}`.",
        "multipart": multipart,
        "params": True,
        "body_union": body_union,
    }
    return ("named", module, name)


def response_type(ep: dict, listed: dict) -> tuple | None:
    if ep["kind"] in ("unit", "binary"):
        return None
    schema = ep["item_schema"]
    rname = ep["ret_name"]
    module = ep["ret_module"]
    if "$ref" in schema:
        comp = component_ref(ref_name(schema["$ref"]))
        if pascal(rname) == comp[2]:
            return comp
        key = (module, pascal(rname))
        if key in TYPES:
            return ("named",) + key
        name = claim(module, pascal(rname))
        TYPES[(module, name)] = {"kind": "alias", "target": comp, "doc": None}
        return ("named", module, name)
    key = (module, pascal(rname))
    if key in TYPES and TYPES[key]["kind"] != "pending":
        return ("named",) + key
    name = claim(module, pascal(rname))
    TYPES[(module, name)] = build_type(schema, module, name)
    return ("named", module, name)


def resolve_listed_alias(pyname: str, module: tuple, section: tuple) -> str | None:
    """Find the spec component behind a type name listed in api.md."""
    if pyname in OVERRIDES.get("type_aliases", {}):
        return OVERRIDES["type_aliases"][pyname]
    by_rust = {pascal(c).lower(): c for c in COMPONENTS}
    by_rust.update({v.lower(): k for k, v in OVERRIDES.get("component_names", {}).items()})
    if pascal(pyname).lower() in by_rust:
        return by_rust[pascal(pyname).lower()]
    for prefix in [pascal("".join(section[: i + 1])) for i in range(len(section))][::-1] + ["Browser", "WebMcp"]:
        cand = (prefix + pascal(pyname)).lower()
        if cand in by_rust:
            return by_rust[cand]
    suffix = [c for c in COMPONENTS if pascal(c).endswith(pascal(pyname))]
    if len(suffix) == 1:
        return suffix[0]
    return None


