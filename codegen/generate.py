def main() -> None:
    methods, listed = parse_api_md()
    endpoints = []
    missing = []
    for m in methods:
        if m["path"] not in SPEC["paths"] or m["verb"] not in SPEC["paths"][m["path"]]:
            missing.append(f"{m['verb']} {m['path']}")
            continue
        endpoints.append(build_endpoint(m))

    # Components first, so their names are claimed before inline types.
    for name in COMPONENTS:
        component_ref(name)

    for ep in endpoints:
        ep["params_ty"] = build_params(ep)
        ep["rt"] = response_type(ep, listed)

    # Aliases for other type names listed in api.md (for example
    # `kernel.types.browsers.Tool` for the `WebMCPTool` component).
    aliases = {}
    for pyname, places in listed.items():
        for module, section in places:
            key = (module, pascal(pyname))
            if key in TYPES or pascal(pyname) in RESERVED_TYPE_NAMES and module == ():
                continue
            comp = resolve_listed_alias(pyname, module, section)
            if comp is None:
                warn(f"listed type {'.'.join(module)}.{pyname} has no matching component")
                continue
            target = component_ref(comp)
            if target == ("named",) + key:
                continue
            TYPES[key] = {"kind": "alias", "target": target, "doc": f"Alias for the `{target[2]}` type."}
            aliases[f"{'::'.join(module) or 'types'}::{pascal(pyname)}"] = target[2]

    scc = compute_sccs()
    for ep in endpoints:
        ep["code"] = emit_method(ep, ep["params_ty"], ep["rt"])
    write_types(emit_types(scc))
    write_resources(build_resource_tree(endpoints))
    write_tests([emit_test(ep, ep["params_ty"], ep["rt"]) for ep in endpoints])

    spec_ops = {f"{v} {p}" for p, it in SPEC["paths"].items() for v in it if v in ("get", "post", "put", "patch", "delete")}
    covered = {f"{ep['verb']} {ep['path']}" for ep in endpoints}
    report = {
        "endpoints": len(endpoints),
        "types": len(TYPES),
        "api_md_methods_missing_from_spec": missing,
        "spec_operations_not_in_api_md": sorted(spec_ops - covered),
        "aliases": aliases,
        "warnings": warnings,
    }
    (ROOT / "codegen/report.json").write_text(json.dumps(report, indent=2) + "\n")
    print(f"generated {len(endpoints)} endpoints, {len(TYPES)} types, {len(warnings)} warnings")
    for w in warnings:
        print("warning:", w)


if __name__ == "__main__":
    main()
