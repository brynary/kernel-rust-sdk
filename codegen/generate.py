#!/usr/bin/env python3
"""Generate the Kernel Rust SDK from the OpenAPI spec and the Python SDK's api.md.

Inputs:
  upstream/openapi.json   The public Kernel OpenAPI spec (request/response shapes).
  upstream/api.python.md  The Python SDK's api.md (resource tree, method names, type names).

Outputs (all overwritten on each run):
  src/types/**            Models, params, and response types.
  src/resources/**        Resource structs with one async method per endpoint.
  tests/api_resources.rs  One mock-server test per endpoint.
  codegen/report.json     Endpoint coverage and naming decisions.

Run: python3 codegen/generate.py
"""

from __future__ import annotations

import json
import re
import sys
from collections import OrderedDict, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def fix_yaml_booleans(node):
    """Undo a YAML 1.1 bug in the published spec: a property key `y` was
    parsed as the boolean true, so it appears as "true" in `properties` and
    as `true` in `required`. The first-party SDKs name these fields `y`."""
    if isinstance(node, dict):
        props = node.get("properties")
        if isinstance(props, dict) and "true" in props and "y" not in props:
            node["properties"] = {("y" if k == "true" else k): v for k, v in props.items()}
            if isinstance(node.get("required"), list):
                node["required"] = ["y" if r is True or r == "true" else r for r in node["required"]]
        for v in node.values():
            fix_yaml_booleans(v)
    elif isinstance(node, list):
        for v in node:
            fix_yaml_booleans(v)
    return node


SPEC = fix_yaml_booleans(json.loads((ROOT / "upstream/openapi.json").read_text()))
API_MD = (ROOT / "upstream/api.python.md").read_text()
OVERRIDES = json.loads((ROOT / "codegen/overrides.json").read_text())
COMPONENTS = SPEC["components"]["schemas"]

HEADER = (
    "// File generated by codegen/generate.py from upstream/openapi.json and\n"
    "// upstream/api.python.md. Do not edit by hand.\n"
)

RUST_KEYWORDS = set(
    "as break const continue crate else enum extern false fn for if impl in let loop match mod "
    "move mut pub ref return self Self static struct super trait true type unsafe use where while "
    "async await dyn abstract become box do final macro override priv typeof unsized virtual yield "
    "try gen".split()
)
NON_RAW = {"self", "Self", "super", "crate"}
# Names that would shadow common prelude items if glob-imported.
RESERVED_TYPE_NAMES = {"Result", "Option", "Box", "Vec", "String", "Error", "Ok", "Err", "Some", "None"}

warnings: list[str] = []


def warn(msg: str) -> None:
    warnings.append(msg)


# ---------------------------------------------------------------------------
# Naming
# ---------------------------------------------------------------------------

WORD_RE = re.compile(r"[A-Z]+(?=[A-Z][a-z])|[A-Z]?[a-z]+[0-9]*|[A-Z]+[0-9]*|[0-9]+")


def words(name: str) -> list[str]:
    out = []
    for part in re.split(r"[^A-Za-z0-9]+", name):
        out += WORD_RE.findall(part)
    return out


def pascal(name: str) -> str:
    s = "".join(w[:1].upper() + w[1:].lower() for w in words(name))
    if not s:
        s = "Empty"
    if s[0].isdigit():
        s = "V" + s
    return s


def snake(name: str) -> str:
    s = "_".join(w.lower() for w in words(name))
    if not s:
        s = "value"
    if s[0].isdigit():
        s = "_" + s
    return s


def ident(name: str) -> str:
    """A Rust identifier for a field or method, using raw identifiers for keywords."""
    if name in NON_RAW:
        return name + "_"
    if name in RUST_KEYWORDS:
        return "r#" + name
    return name


def singular(name: str) -> str:
    if name.endswith("ies") and len(name) > 4:
        return name[:-3] + "y"
    if name.endswith("sses"):
        return name[:-2]
    if name.endswith("s") and not name.endswith(("ss", "us", "is")) and len(name) > 3:
        return name[:-1]
    return name


def doc_lines(text: str | None, indent: str = "") -> str:
    """Render a description as rustdoc comments, escaped so rustdoc does not
    treat it as links, HTML, or doctests."""
    if not text:
        return ""
    out = []
    in_fence = False
    for line in text.strip().splitlines():
        line = line.strip()
        if line.startswith("```"):
            out.append("```text" if not in_fence else "```")
            in_fence = not in_fence
            continue
        if not in_fence:
            links = []

            def keep(m):
                links.append(m.group(0))
                return f"\x00{len(links) - 1}\x00"

            line = re.sub(r"\[[^\]]+\]\(https?://[^)\s]+\)", keep, line)
            line = (
                line.replace("\\", "\\\\")
                .replace("[", "\\[")
                .replace("]", "\\]")
                .replace("<", "\\<")
                .replace(">", "\\>")
            )
            line = re.sub(r"\b(https?://[^\s)>\]\\]+[^\s)>\].,;:\\])", r"<\1>", line)
            line = re.sub(r"\x00(\d+)\x00", lambda m: links[int(m.group(1))], line)
        out.append(line)
    if in_fence:
        out.append("```")
    return "".join(f"{indent}///{(' ' + l) if l else ''}\n" for l in out)


def rust_str(s: str) -> str:
    return json.dumps(s)


# ---------------------------------------------------------------------------
# Schema helpers
# ---------------------------------------------------------------------------


def ref_name(ref: str) -> str:
    return ref.split("/")[-1]


def resolve(schema: dict) -> dict:
    seen = 0
    while "$ref" in schema and seen < 50:
        schema = COMPONENTS[ref_name(schema["$ref"])]
        seen += 1
    return schema


def merged_object(schema: dict) -> tuple[dict, list[str]] | None:
    """Return (properties, required) for an object schema, merging allOf.
    Return None if the schema is not an object with properties."""
    schema_r = resolve(schema)
    props: OrderedDict = OrderedDict()
    required: list[str] = []
    if "allOf" in schema_r:
        for part in schema_r["allOf"]:
            m = merged_object(part)
            if m is None:
                return None
            props.update(m[0])
            required += [r for r in m[1] if r not in required]
    if "properties" in schema_r:
        props.update(schema_r["properties"])
        required += [r for r in schema_r.get("required", []) if r not in required]
    if not props and "allOf" not in schema_r:
        return None
    return props, required


def is_constraint_only(variants: list[dict]) -> bool:
    """True for oneOf lists like [{required: [id]}, {required: [name]}]."""
    return all(set(v.keys()) <= {"required", "description", "title", "not", "properties"} and "$ref" not in v
               and not v.get("properties") for v in variants)


def const_value(schema: dict):
    s = resolve(schema)
    if "const" in s:
        return s["const"]
    if isinstance(s.get("enum"), list) and len(s["enum"]) == 1:
        return s["enum"][0]
    return None


def nullable(schema: dict) -> bool:
    if schema.get("nullable"):
        return True
    t = schema.get("type")
    return isinstance(t, list) and "null" in t


def is_binary(schema: dict) -> bool:
    s = resolve(schema)
    return s.get("type") == "string" and s.get("format") == "binary"


# ---------------------------------------------------------------------------
# IR
# ---------------------------------------------------------------------------
# TypeRef is a tuple:
#   ("prim", rust)          String, bool, i64, f64, Value, DateTime, NaiveDate, FileUpload
#   ("named", module, name) module is a tuple like ("browsers", "fs")
#   ("vec", TypeRef) / ("map", TypeRef)

TYPES: dict[tuple, dict] = OrderedDict()  # (module, name) -> type def
COMPONENT_TYPES: dict[str, tuple] = {}  # spec component name -> ("named", (), rust name)


def claim(module: tuple, name: str) -> str:
    base = name
    i = 2
    while (module, name) in TYPES:
        name = f"{base}{i}"
        i += 1
    if name != base:
        warn(f"type name {base} taken in {'::'.join(module) or 'types'}; using {name}")
    TYPES[(module, name)] = {"kind": "pending"}
    return name


def component_ref(name: str) -> tuple:
    if name not in COMPONENT_TYPES:
        rname = claim((), OVERRIDES.get("component_names", {}).get(name) or pascal(name))
        COMPONENT_TYPES[name] = ("named", (), rname)
        TYPES[((), rname)] = build_type(COMPONENTS[name], (), rname)
    return COMPONENT_TYPES[name]


def type_of(schema: dict, module: tuple, ctx: str, multipart: bool = False) -> tuple:
    """Map a property schema to a TypeRef, generating named types for inline
    objects, enums, and unions. `ctx` names any generated type."""
    if "$ref" in schema:
        return component_ref(ref_name(schema["$ref"]))
    if "allOf" in schema and len(schema["allOf"]) == 1 and "properties" not in schema:
        return type_of(schema["allOf"][0], module, ctx, multipart)
    t = schema.get("type")
    if isinstance(t, list):
        non_null = [x for x in t if x != "null"]
        if len(non_null) == 1:
            return type_of({**schema, "type": non_null[0]}, module, ctx, multipart)
        return ("prim", "Value")
    if multipart and is_binary(schema):
        return ("prim", "FileUpload")
    if "allOf" in schema or "oneOf" in schema or "anyOf" in schema:
        if ("oneOf" in schema and "properties" in schema and is_constraint_only(schema["oneOf"])):
            pass  # a plain object; fall through
        else:
            name = claim(module, ctx)
            TYPES[(module, name)] = build_type(schema, module, name, multipart)
            return ("named", module, name)
    if t == "string":
        if isinstance(schema.get("enum"), list) and len(schema["enum"]) > 1:
            name = claim(module, ctx)
            TYPES[(module, name)] = build_type(schema, module, name)
            return ("named", module, name)
        fmt = schema.get("format")
        if fmt == "date-time":
            return ("prim", "DateTime")
        if fmt == "date":
            return ("prim", "NaiveDate")
        return ("prim", "String")
    if t == "integer":
        return ("prim", "i64")
    if t == "number":
        return ("prim", "f64")
    if t == "boolean":
        return ("prim", "bool")
    if t == "array":
        items = schema.get("items", {})
        return ("vec", type_of(items, module, singular(ctx), multipart))
    if t == "object" or "properties" in schema:
        if schema.get("properties"):
            name = claim(module, ctx)
            TYPES[(module, name)] = build_type(schema, module, name, multipart)
            return ("named", module, name)
        ap = schema.get("additionalProperties")
        if isinstance(ap, dict) and ap:
            return ("map", type_of(ap, module, ctx + "Value"))
        return ("map", ("prim", "Value"))
    if "enum" in schema and len(schema["enum"]) > 1 and all(isinstance(v, str) for v in schema["enum"]):
        name = claim(module, ctx)
        TYPES[(module, name)] = build_type({**schema, "type": "string"}, module, name)
        return ("named", module, name)
    if "const" in schema and isinstance(schema["const"], str):
        return ("prim", "String")
    return ("prim", "Value")


def build_fields(props: dict, required: list[str], module: tuple, owner: str, multipart: bool = False) -> list[dict]:
    fields = []
    used = set()
    for wire, pschema in props.items():
        if not isinstance(pschema, dict):
            continue
        rname = snake(wire)
        while rname in used:
            rname += "_"
        used.add(rname)
        ty = type_of(pschema, module, owner + pascal(wire), multipart)
        cv = pschema.get("const") if isinstance(pschema.get("const"), str) else None
        if cv is None and isinstance(pschema.get("enum"), list) and len(pschema["enum"]) == 1 and isinstance(pschema["enum"][0], str):
            cv = pschema["enum"][0]
        desc = pschema.get("description") or resolve(pschema).get("description") if "$ref" in pschema else pschema.get("description")
        fields.append({
            "name": rname,
            "wire": wire,
            "ty": ty,
            "required": wire in required,
            "req_index": required.index(wire) if wire in required else None,
            "nullable": nullable(pschema),
            "doc": desc,
            "const": cv,
            "location": "body",
            "explode": False,
            "file": multipart and contains_file(ty),
        })
    return fields


def contains_file(ty: tuple, seen=None) -> bool:
    seen = seen or set()
    if ty == ("prim", "FileUpload"):
        return True
    if ty[0] in ("vec", "map"):
        return contains_file(ty[1], seen)
    if ty[0] == "named":
        key = (ty[1], ty[2])
        if key in seen:
            return False
        seen.add(key)
        t = TYPES.get(key, {})
        return t.get("kind") == "struct" and any(contains_file(f["ty"], seen) for f in t["fields"])
    return False


def union_variant_names(names: list[str]) -> list[str]:
    split = [words(n) for n in names]
    if len(split) > 1:
        pre = 0
        while all(len(w) > pre + 1 for w in split) and len({tuple(w[: pre + 1]) for w in split}) == 1:
            pre += 1
        suf = 0
        while all(len(w) > pre + suf + 1 for w in split) and len({tuple(w[len(w) - suf - 1:]) for w in split}) == 1:
            suf += 1
        short = [pascal("".join(w[pre: len(w) - suf])) for w in split]
        if len(set(short)) == len(short) and all(short):
            return short
    return [pascal(n) for n in names]


def build_type(schema: dict, module: tuple, name: str, multipart: bool = False) -> dict:
    doc = schema.get("description")
    if "$ref" in schema:
        return {"kind": "alias", "target": component_ref(ref_name(schema["$ref"])), "doc": doc}

    variants_key = "oneOf" if "oneOf" in schema else "anyOf" if "anyOf" in schema else None
    if variants_key and not ("properties" in schema and is_constraint_only(schema[variants_key])):
        variants = schema[variants_key]
        disc = schema.get("discriminator", {}).get("propertyName")
        if not disc and variants and all("$ref" in v for v in variants):
            # No discriminator in the spec. If every variant has the same
            # property with a distinct constant value, use it as one, so
            # decoding does not pick the first variant that happens to fit.
            objs = [merged_object(v) for v in variants]
            if all(objs):
                common = set.intersection(*[set(o[0]) for o in objs])
                for prop in sorted(common):
                    vals = [const_value(o[0][prop]) for o in objs]
                    if all(isinstance(v, str) for v in vals) and len(set(vals)) == len(vals):
                        disc = prop
                        break
        raw_names = []
        tys = []
        for i, v in enumerate(variants):
            if "$ref" in v:
                raw_names.append(ref_name(v["$ref"]))
                tys.append(component_ref(ref_name(v["$ref"])))
            else:
                t = v.get("type")
                label = {"boolean": "Bool", "string": "String", "integer": "Integer", "number": "Number",
                         "array": "Array", "object": "Object"}.get(t if isinstance(t, str) else "", f"Variant{i}")
                raw_names.append(label)
                tys.append(type_of(v, module, name + label, multipart))
        vnames = union_variant_names(raw_names) if all("$ref" in v for v in variants) else raw_names
        disc_values: dict[str, list] = {}
        if disc:
            mapping = schema.get("discriminator", {}).get("mapping", {})
            for vn, v in zip(vnames, variants):
                vals = [k for k, r in mapping.items() if "$ref" in v and r == v["$ref"]]
                if not vals:
                    m = merged_object(v)
                    if m and disc in m[0]:
                        p = resolve(m[0][disc])
                        if "const" in p:
                            vals = [p["const"]]
                        elif isinstance(p.get("enum"), list):
                            vals = list(p["enum"])
                if not vals:
                    warn(f"union {name}: variant {vn} has no discriminator value")
                disc_values[vn] = vals
        return {"kind": "union", "variants": list(zip(vnames, tys)), "disc": disc,
                "disc_values": disc_values, "doc": doc}

    if "allOf" in schema:
        m = merged_object(schema)
        if m is None:
            if len(schema["allOf"]) == 1:
                return {"kind": "alias", "target": type_of(schema["allOf"][0], module, name), "doc": doc}
            return {"kind": "alias", "target": ("prim", "Value"), "doc": doc}
        props, required = m
        return {"kind": "struct", "fields": build_fields(props, required, module, name, multipart), "doc": doc,
                "multipart": multipart}

    t = schema.get("type")
    if t == "string" and isinstance(schema.get("enum"), list) and len(schema["enum"]) > 1:
        varnames = schema.get("x-enum-varnames") or []
        values = []
        used = set()
        stripped = [pascal(x) for x in varnames]
        # x-enum-varnames often repeat the enum's name ("StatusRunning");
        # drop the longest shared prefix so variants read Status::Running.
        if len(stripped) > 1:
            pre = 0
            ws = [words(x) for x in stripped]
            while all(len(w) > pre + 1 for w in ws) and len({tuple(w[: pre + 1]) for w in ws}) == 1:
                pre += 1
            short = [pascal("".join(w[pre:])) for w in ws]
            if pre and len(set(short)) == len(short):
                stripped = short
        for i, v in enumerate(schema["enum"]):
            vn = stripped[i] if i < len(stripped) else pascal(str(v))
            if vn == "Unknown":
                vn = "UnknownValue"
            while vn in used:
                vn += "_"
            used.add(vn)
            values.append((vn, str(v)))
        return {"kind": "enum", "values": values, "doc": doc}

    if (t == "object" or "properties" in schema) and schema.get("properties"):
        return {"kind": "struct", "fields": build_fields(schema["properties"], schema.get("required", []), module, name, multipart),
                "doc": doc, "multipart": multipart}

    # Primitive, array, or map component: a type alias.
    inner = dict(schema)
    inner.pop("description", None)
    target = type_of(inner, module, name + "Item" if t == "array" else name + "Value", multipart)
    if target == ("named", module, name):
        target = ("prim", "Value")
    return {"kind": "alias", "target": target, "doc": doc}


