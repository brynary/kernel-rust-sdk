def direct_edges(t: dict) -> list[tuple]:
    def direct(ty):
        if ty[0] == "named":
            return [(ty[1], ty[2])]
        return []
    if t["kind"] == "struct":
        return [e for f in t["fields"] for e in direct(f["ty"])]
    if t["kind"] == "union":
        return [e for _, ty in t["variants"] for e in direct(ty)]
    if t["kind"] == "alias":
        return direct(t["target"])
    return []


def compute_sccs() -> dict[tuple, int]:
    index = {}
    low = {}
    stack = []
    on = set()
    comp = {}
    counter = [0]
    ncomp = [0]
    sys.setrecursionlimit(100000)

    def visit(v):
        index[v] = low[v] = counter[0]
        counter[0] += 1
        stack.append(v)
        on.add(v)
        for w in direct_edges(TYPES[v]):
            if w not in TYPES:
                continue
            if w not in index:
                visit(w)
                low[v] = min(low[v], low[w])
            elif w in on:
                low[v] = min(low[v], index[w])
        if low[v] == index[v]:
            while True:
                w = stack.pop()
                on.discard(w)
                comp[w] = ncomp[0]
                if w == v:
                    break
            ncomp[0] += 1

    for v in list(TYPES):
        if v not in index:
            visit(v)
    return comp


