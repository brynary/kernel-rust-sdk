METHOD_RE = re.compile(
    r'^- <code title="(?P<verb>\w+) (?P<path>[^"]+)">client\.(?P<res>[\w.]+)\.<a href="[^"]*">(?P<name>\w+)</a>'
    r"\((?P<args>.*?)\) -> (?P<ret>.*)</code>$"
)
LINK_RE = re.compile(r'<a href="\.?/?src/kernel/types/(?P<path>[\w/]+)\.py">(?P<text>[^<]+)</a>')


def module_of(type_path: str) -> tuple:
    parts = tuple(type_path.split("/")[:-1])
    if parts[:1] == ("shared",):
        parts = parts[1:]
    return parts


def parse_api_md():
    methods = []
    listed: dict[str, list[tuple]] = defaultdict(list)  # name -> modules
    section: list[str] = []
    in_block = None
    for line in API_MD.splitlines():
        h = re.match(r"^(#+) (.*)", line)
        if h:
            section = section[: len(h.group(1)) - 1] + [h.group(2)]
            continue
        m = re.match(r"^from kernel\.types\.?([\w.]*) import \(?([\w, ]*)\)?$", line)
        if m:
            mod = tuple(p for p in m.group(1).split(".") if p and p != "shared")
            for n in [x.strip() for x in m.group(2).split(",") if x.strip()]:
                listed[n].append((mod, tuple(section)))
            in_block = mod if line.rstrip().endswith("(") else None
            continue
        if in_block is not None:
            m = re.match(r"^\s+(\w+),?$", line)
            if m:
                listed[m.group(1)].append((in_block, tuple(section)))
                continue
            if line.startswith(")"):
                in_block = None
                continue
        m = METHOD_RE.match(line)
        if m:
            d = m.groupdict()
            params_link = None
            for lm in LINK_RE.finditer(d["args"]):
                if lm.group("text") == "params":
                    params_link = lm.group("path")
            ret = d["ret"]
            rlinks = list(LINK_RE.finditer(ret))
            ret_text = re.sub(r"<[^>]+>", "", ret).strip()
            ret_module = module_of(rlinks[0].group("path")) if rlinks else ()
            methods.append({
                "verb": d["verb"],
                "path": d["path"],
                "resource": d["res"].split("."),
                "name": d["name"],
                "params_link": params_link,
                "ret_text": ret_text,
                "ret_module": ret_module,
                "section": tuple(section),
            })
    return methods, listed


