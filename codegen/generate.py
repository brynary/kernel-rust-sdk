def rs(ty: tuple, cur: tuple, boxed: bool = False) -> str:
    kind = ty[0]
    if kind == "prim":
        return {
            "String": "String",
            "bool": "bool",
            "i64": "i64",
            "f64": "f64",
            "Value": "serde_json::Value",
            "DateTime": "chrono::DateTime<chrono::Utc>",
            "NaiveDate": "chrono::NaiveDate",
            "FileUpload": "crate::FileUpload",
        }[ty[1]]
    if kind == "vec":
        return f"Vec<{rs(ty[1], cur)}>"
    if kind == "map":
        return f"std::collections::HashMap<String, {rs(ty[1], cur)}>"
    if kind == "named":
        mod, name = ty[1], ty[2]
        path = name if mod == cur else "crate::types::" + "".join(m + "::" for m in mod) + name
        return f"Box<{path}>" if boxed else path
    raise ValueError(ty)


def is_enum(ty: tuple) -> bool:
    return ty[0] == "named" and TYPES.get((ty[1], ty[2]), {}).get("kind") == "enum"


def is_vec_or_map(ty: tuple) -> bool:
    return ty[0] in ("vec", "map")


def emit_struct(key: tuple, t: dict, scc: dict) -> str:
    module, name = key
    out = doc_lines(t.get("doc"))
    multipart = t.get("multipart")
    if multipart:
        out += "#[derive(Debug, Clone, PartialEq)]\n"
    else:
        out += "#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]\n"
    out += f"pub struct {name} {{\n"
    ctor_args = []
    ctor_body = []
    all_optional = True
    # Constructor arguments follow the spec's `required` order (for example
    # `(x, y)` and `(src_path, dest_path)`), not the alphabetical field order.
    arg_order = {}
    for f in t["fields"]:
        boxed = f["ty"][0] == "named" and scc.get((f["ty"][1], f["ty"][2])) == scc.get(key) and (f["ty"][1], f["ty"][2]) in TYPES
        inner = rs(f["ty"], module, boxed)
        optional = not f["required"] or f["nullable"]
        fty = f"Option<{inner}>" if optional else inner
        out += doc_lines(f.get("doc"), "    ")
        attrs = []
        fname = ident(f["name"])
        if not multipart:
            if fname.removeprefix("r#") != f["wire"]:
                attrs.append(f"rename = {rust_str(f['wire'])}")
            if not f["required"]:
                attrs.append('default, skip_serializing_if = "Option::is_none"')
            elif f["nullable"] or is_vec_or_map(f["ty"]) or f["ty"][0] == "prim" or is_enum(f["ty"]):
                # Like the first-party SDKs, do not fail when the server
                # omits a required field; use the zero value instead.
                attrs.append("default")
            if attrs:
                out += f"    #[serde({', '.join(attrs)})]\n"
        out += f"    pub {fname}: {fty},\n"
        if f["required"] and not f["nullable"]:
            if f["const"] is not None and f["ty"] == ("prim", "String"):
                ctor_body.append(f"{fname}: {rust_str(f['const'])}.to_owned()")
            else:
                all_optional = False
                arg = f["name"].removeprefix("r#")
                arg = arg + "_" if arg in RUST_KEYWORDS or arg in NON_RAW else arg
                val = f"{arg}.into()"
                if boxed:
                    val = f"Box::new({arg}.into())"
                ctor_args.append(f"{arg}: impl Into<{rs(f['ty'], module)}>")
                ri = f.get("req_index")
                arg_order[ctor_args[-1]] = (ri if ri is not None else 1_000_000, len(ctor_args))
                ctor_body.append(f"{fname}: {val}")
        else:
            ctor_body.append(f"{fname}: None" if optional else f"{fname}: Default::default()")
    out += "}\n\n"
    out += f"impl {name} {{\n"
    out += f"    /// Create a `{name}` with the required fields set.\n"
    out += "    #[allow(clippy::too_many_arguments, clippy::new_without_default)]\n"
    ctor_args.sort(key=lambda a: arg_order.get(a, (1_000_000, 0)))
    out += f"    pub fn new({', '.join(ctor_args)}) -> Self {{\n"
    out += "        Self {\n" + "".join(f"            {b},\n" for b in ctor_body) + "        }\n    }\n"
    if multipart and t.get("params"):
        out += "\n    pub(crate) fn to_form(&self) -> crate::runtime::multipart::MultipartForm {\n"
        out += "        let mut form = crate::runtime::multipart::MultipartForm::new();\n"
        out += "        crate::runtime::multipart::MultipartEncode::encode(self, \"\", &mut form);\n"
        out += "        form\n    }\n"
    out += "}\n"
    if all_optional:
        out += f"\nimpl Default for {name} {{\n    fn default() -> Self {{\n        Self::new()\n    }}\n}}\n"
    if multipart:
        out += f"\nimpl crate::runtime::multipart::MultipartEncode for {name} {{\n"
        out += "    fn encode(&self, key: &str, form: &mut crate::runtime::multipart::MultipartForm) {\n"
        out += "        use crate::runtime::multipart::MultipartForm;\n"
        for f in t["fields"]:
            fname = ident(f["name"])
            k = f"&MultipartForm::child(key, {rust_str(f['wire'])})"
            if f["file"]:
                out += f"        crate::runtime::multipart::MultipartEncode::encode(&self.{fname}, {k}, form);\n"
            else:
                out += f"        form.value({k}, &self.{fname});\n"
        out += "    }\n}\n"
    return out


def emit_enum(key: tuple, t: dict) -> str:
    name = key[1]
    out = "crate::string_enum! {\n"
    out += doc_lines(t.get("doc"), "    ")
    out += f"    {name} {{\n"
    for vn, val in t["values"]:
        out += f"        {vn} = {rust_str(val)},\n"
    out += "    }\n}\n"
    return out


def emit_union(key: tuple, t: dict, scc: dict) -> str:
    module, name = key
    out = doc_lines(t.get("doc"))
    disc = t["disc"]
    out += "#[derive(Debug, Clone, PartialEq, serde::Serialize" + ("" if disc else ", serde::Deserialize") + ")]\n"
    out += "#[serde(untagged)]\n#[non_exhaustive]\n"
    out += f"pub enum {name} {{\n"
    for vn, ty in t["variants"]:
        boxed = ty[0] == "named" and scc.get((ty[1], ty[2])) == scc.get(key)
        out += f"    {vn}({rs(ty, module, boxed)}),\n"
    out += "    /// A value not known to this version of the SDK.\n    Unknown(serde_json::Value),\n}\n"
    if disc:
        out += f"\nimpl<'de> serde::Deserialize<'de> for {name} {{\n"
        out += "    fn deserialize<D: serde::Deserializer<'de>>(d: D) -> Result<Self, D::Error> {\n"
        out += "        let value = <serde_json::Value as serde::Deserialize>::deserialize(d)?;\n"
        out += f"        let tag = value.get({rust_str(disc)}).and_then(|t| t.as_str()).map(str::to_owned);\n"
        out += "        match tag.as_deref() {\n"
        for vn, ty in t["variants"]:
            vals = t["disc_values"].get(vn) or []
            if not vals:
                continue
            boxed = ty[0] == "named" and scc.get((ty[1], ty[2])) == scc.get(key)
            wrap = f"|v| Self::{vn}(Box::new(v))" if boxed else f"Self::{vn}"
            pat = " | ".join(f"Some({rust_str(str(v))})" for v in vals)
            out += f"            {pat} => serde_json::from_value(value).map({wrap}).map_err(serde::de::Error::custom),\n"
        out += "            _ => Ok(Self::Unknown(value)),\n        }\n    }\n}\n"
    for vn, ty in t["variants"]:
        if ty[0] == "named" and [x for _, x in t["variants"]].count(ty) == 1:
            boxed = scc.get((ty[1], ty[2])) == scc.get(key)
            path = rs(ty, module)
            val = "Box::new(v)" if boxed else "v"
            out += f"\nimpl From<{path}> for {name} {{\n    fn from(v: {path}) -> Self {{\n        Self::{vn}({val})\n    }}\n}}\n"
    return out


def emit_alias(key: tuple, t: dict) -> str:
    return doc_lines(t.get("doc")) + f"pub type {key[1]} = {rs(t['target'], key[0])};\n"


def emit_types(scc: dict) -> dict[tuple, str]:
    by_module: dict[tuple, list[str]] = defaultdict(list)
    for key, t in TYPES.items():
        if t["kind"] == "struct":
            code = emit_struct(key, t, scc)
        elif t["kind"] == "enum":
            code = emit_enum(key, t)
        elif t["kind"] == "union":
            code = emit_union(key, t, scc)
        elif t["kind"] == "alias":
            code = emit_alias(key, t)
        else:
            raise ValueError(f"unfinished type {key}")
        by_module[key[0]].append(code)
    return by_module


def write_types(by_module: dict[tuple, list[str]]) -> None:
    out_dir = ROOT / "src/types"
    if out_dir.exists():
        for p in sorted(out_dir.rglob("*.rs"), reverse=True):
            p.unlink()
    modules = set(by_module) | {()}
    for m in list(modules):
        for i in range(len(m)):
            modules.add(m[:i])
    for m in sorted(modules):
        children = sorted({c[len(m)] for c in modules if len(c) == len(m) + 1 and c[: len(m)] == m})
        path = out_dir.joinpath(*m, "mod.rs")
        path.parent.mkdir(parents=True, exist_ok=True)
        body = HEADER + "\n"
        if m == ():
            body += "//! Request and response types.\n//!\n//! The module tree mirrors `kernel.types` in the Python SDK.\n\n"
        body += "#![allow(clippy::large_enum_variant, clippy::doc_lazy_continuation)]\n\n" if m == () else ""
        for c in children:
            body += f"pub mod {c};\n"
        if children:
            body += "\n"
        body += "\n".join(by_module.get(m, []))
        path.write_text(body)


def rust_path_expr(path: str, path_params: list[dict]) -> str:
    fmt = path
    args = []
    for p in path_params:
        fmt = fmt.replace("{" + p["name"] + "}", "{}")
        args.append(f"path_segment({ident(snake(p['name']))})")
    if not args:
        return f"{rust_str(path)}.to_owned()"
    return f"format!({rust_str(fmt)}, {', '.join(args)})"


def method_return(ep: dict, rt: tuple | None, cur: tuple) -> tuple[str, str]:
    k = ep["kind"]
    t = rs(rt, cur) if rt else None
    return {
        "unit": ("()", "execute_unit"),
        "json": (t, "execute"),
        "optional": (f"Option<{t}>", "execute_optional"),
        "binary": ("BinaryResponse", "execute_binary"),
        "sse": (f"EventStream<{t}>", "execute_stream"),
        "offset_page": (f"OffsetPagination<{t}>", "execute_offset_page"),
        "token_page": (f"PageTokenPagination<{t}>", "execute_token_page"),
    }[k]


def emit_method(ep: dict, params_ty, rt) -> str:
    op = ep["op"]
    doc = op.get("summary", "")
    if op.get("description") and op.get("description") != doc:
        doc = (doc + "\n\n" if doc else "") + op["description"]
    doc = (doc + "\n\n" if doc else "") + f"`{ep['verb'].upper()} {ep['path']}`"
    ret, exec_fn = method_return(ep, rt, ("__resources__",))
    args = ["&self"] + [f"{ident(snake(p['name']))}: &str" for p in ep["path_params"]]
    if ep["body_kind"] == "bytes":
        args.append("contents: impl Into<bytes::Bytes>")
    if params_ty:
        args.append(f"params: {rs(params_ty, ('__resources__',))}")
    out = doc_lines(doc, "    ")
    out += f"    pub async fn {ident(ep['name'])}({', '.join(args)}) -> Result<{ret}> {{\n"
    mutable = ep["kind"] == "binary" or ep["body_kind"] == "bytes" or (params_ty and (
        TYPES[(params_ty[1], params_ty[2])].get("multipart") or ep["body_kind"] == "json"
        or any(f["location"] in ("query", "header") for f in TYPES[(params_ty[1], params_ty[2])]["fields"])))
    out += f"        let {'mut ' if mutable else ''}req = ApiRequest::new(Method::{ep['verb'].upper()}, {rust_path_expr(ep['path'], ep['path_params'])});\n"
    if params_ty:
        pdef = TYPES[(params_ty[1], params_ty[2])]
        if pdef.get("multipart"):
            out += "        req = req.multipart(params.to_form());\n"
        else:
            q = [f for f in pdef["fields"] if f["location"] == "query"]
            moves = q or any(f["location"] == "header" for f in pdef["fields"]) or pdef.get("body_union")
            out += f"        let {'mut ' if moves else ''}fields = to_fields(&params)?;\n"
            if q:
                keys = ", ".join(rust_str(f["wire"]) for f in q if not f["explode"])
                ex = ", ".join(rust_str(f["wire"]) for f in q if f["explode"])
                out += f"        req = req.query_from(&mut fields, &[{keys}], &[{ex}]);\n"
            for f in pdef["fields"]:
                if f["location"] == "header":
                    out += f"        req = req.header_from(&mut fields, {rust_str(f['wire'])});\n"
            if ep["body_kind"] == "json":
                if pdef.get("body_union"):
                    out += "        req = req.json(&fields.remove(\"body\").unwrap_or_default())?;\n"
                else:
                    out += "        req = req.json(&fields)?;\n"
    if ep["body_kind"] == "bytes":
        out += "        req = req.bytes(contents.into(), \"application/octet-stream\");\n"
    if ep["kind"] == "binary":
        accept = [ct for r in ep["op"]["responses"].values() for ct in (resolve_response(r).get("content") or {})]
        accept = [a for a in accept if a not in ("application/json", "application/problem+json")]
        if accept:
            out += f"        req = req.header(\"accept\", Some(&{rust_str(', '.join(dict.fromkeys(accept)))}));\n"
    out += f"        self.client.{exec_fn}(req).await\n    }}\n"
    return out


def build_resource_tree(endpoints):
    tree = {"children": OrderedDict(), "methods": []}
    for ep in endpoints:
        node = tree
        for seg in ep["resource"]:
            node = node["children"].setdefault(seg, {"children": OrderedDict(), "methods": []})
        node["methods"].append(ep)
    return tree


def emit_resource(name: str, node: dict, path: list[str], indent: str = "") -> str:
    struct = pascal(name)
    title = ".".join(path)
    out = ""
    out += f"{indent}/// Methods for `client.{title}`.\n"
    out += f"{indent}#[derive(Debug, Clone, Copy)]\n"
    out += f"{indent}pub struct {struct}<'a> {{\n{indent}    pub(crate) client: &'a Kernel,\n{indent}}}\n\n"
    out += f"{indent}impl<'a> {struct}<'a> {{\n"
    body = ""
    for child in node["children"]:
        body += f"/// Methods for `client.{title}.{child}`.\n"
        body += f"pub fn {ident(child)}(&self) -> {child}::{pascal(child)}<'a> {{\n"
        body += f"    {child}::{pascal(child)} {{ client: self.client }}\n}}\n\n"
    for ep in node["methods"]:
        body += ep["code"].replace("\n    ", "\n").removeprefix("    ") + "\n"
    body = body.rstrip("\n") + "\n"
    out += "".join((indent + "    " + l if l.strip() else "") + "\n" for l in body.splitlines())
    out += f"{indent}}}\n"
    for child, cnode in node["children"].items():
        out += f"\n{indent}pub mod {child} {{\n"
        out += f"{indent}    #[allow(unused_imports)]\n{indent}    use crate::runtime::prelude::*;\n\n"
        out += emit_resource(child, cnode, path + [child], indent + "    ")
        out += f"{indent}}}\n"
    return out


def write_resources(tree) -> None:
    out_dir = ROOT / "src/resources"
    if out_dir.exists():
        for p in out_dir.glob("*.rs"):
            p.unlink()
    out_dir.mkdir(parents=True, exist_ok=True)
    mod = HEADER + "\n//! API resources. Reach them from the client, for example `client.browsers()`.\n\n"
    accessors = ""
    for name, node in tree["children"].items():
        mod += f"pub mod {name};\n"
        accessors += f"    /// Methods for `client.{name}`.\n"
        accessors += f"    pub fn {ident(name)}(&self) -> {name}::{pascal(name)}<'_> {{\n"
        accessors += f"        {name}::{pascal(name)} {{ client: self }}\n    }}\n\n"
        code = HEADER + "\n#[allow(unused_imports)]\nuse crate::runtime::prelude::*;\n\n"
        code += emit_resource(name, node, [name])
        (out_dir / f"{name}.rs").write_text(code)
    mod += "\nuse crate::Kernel;\n\nimpl Kernel {\n" + accessors.rstrip("\n") + "\n}\n"
    (out_dir / "mod.rs").write_text(mod)


